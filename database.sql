CREATE DATABASE IF NOT EXISTS radius_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE radius_db;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS radius_users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  legacy_id VARCHAR(80) NULL,
  username VARCHAR(191) NOT NULL UNIQUE,
  firstname VARCHAR(120) NOT NULL DEFAULT '',
  lastname VARCHAR(120) NOT NULL DEFAULT '',
  password_value TEXT NOT NULL,
  csi VARCHAR(64) NOT NULL DEFAULT '',
  csi_type ENUM('bound','wildcard','none') NOT NULL DEFAULT 'none',
  notes LONGTEXT NULL,
  added_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_name (lastname, firstname),
  INDEX idx_csi_type (csi_type)
) ENGINE=InnoDB;
